SPEC_BY_KEY: dict[str, WorkflowSpec] = {spec.key: spec for spec in SPECS}

# 动作名 -> 归属模块，用于识别“拿着别的模块的动作到这里发起”的越权请求。
ACTION_OWNER: dict[str, WorkflowSpec] = {
    action: spec for spec in SPECS for action in spec.actions
}


def get_spec(module: str) -> WorkflowSpec | None:
    return SPEC_BY_KEY.get(module)


def all_meta() -> dict[str, Any]:
    """GET /api/workflows 的返回：跨页面读取同一份动作口径。"""
    return {
        "roles": list(ROLE_STEPS),
        "modules": [spec.meta() for spec in SPECS],
    }
