"""统一动作状态机：二十个业务模块的状态序、动作序与授权口径只在这一份台账里维护。

约定（所有模块一致，动作名保持对外不变）：
- 每条记录沿 ``statuses`` 从低到高单向流转，``actions[k]`` 恒等于
  「statuses[k] -> statuses[k+1]」这一档，只许逐级前进，不许回退或跳档。
- 每一档动作绑定一个角色：经办人发起第 1 档、复核人发起第 2 档、审批人发起第 3 档。
- 服务层、接口层、前端可执行动作都从这里读数，杜绝各处各抄一份后对不上。
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

# 三档动作分别需要的授权角色（顺序即动作档序）
ROLE_STEPS: tuple[str, str, str] = ("经办人", "复核人", "审批人")


@dataclass(frozen=True)
class WorkflowSpec:
    """单个业务模块的状态机定义。"""

    key: str
    label: str  # 接口/提示语里对记录的称呼，如“锅炉”“维保记录”
    keyword_field: str  # 列表关键字检索所依据的编号字段
    required_fields: tuple[str, ...]  # 登记时的必填字段
    list_fields: tuple[str, ...]  # 列表/导出展示的字段列
    statuses: tuple[str, ...]  # 状态序列（4 档）
    actions: tuple[str, ...]  # 动作序列（3 档，actions[k] 推进 statuses[k] -> statuses[k+1]）

    @property
    def terminal_status(self) -> str:
        return self.statuses[-1]

    def step_of_action(self, action: str) -> int | None:
        """返回动作所在的档序（从 0 起）；不属于本模块时返回 None。"""
        try:
            return self.actions.index(action)
        except ValueError:
            return None

    def role_for_action(self, action: str) -> str | None:
        step = self.step_of_action(action)
        return ROLE_STEPS[step] if step is not None else None

    def meta(self) -> dict[str, Any]:
        """供 /api/workflows 与跨页对齐使用的只读描述。"""
        return {
            "key": self.key,
            "label": self.label,
            "statuses": list(self.statuses),
            "actions": [
                {
                    "name": action,
                    "from": self.statuses[index],
                    "to": self.statuses[index + 1],
                    "requiredRole": ROLE_STEPS[index],
                    "step": index,
                }
                for index, action in enumerate(self.actions)
            ],
            "terminalStatus": self.terminal_status,
            "roles": list(ROLE_STEPS),
        }


def _spec(
    key: str,
    label: str,
    keyword_field: str,
    required: tuple[str, str, str],
    list_fields: tuple[str, ...],
    statuses: tuple[str, str, str, str],
    actions: tuple[str, str, str],
) -> WorkflowSpec:
    return WorkflowSpec(
        key=key,
        label=label,
        keyword_field=keyword_field,
        required_fields=required,
        list_fields=list_fields,
        statuses=statuses,
        actions=actions,
    )


